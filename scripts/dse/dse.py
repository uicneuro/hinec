def cmd_serve(args):
    import base64
    import secrets
    from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
    d = Path(args.dir)
    status_path = d / "status.json"
    if not status_path.exists():
        print(f"error: no status.json in {d}", file=sys.stderr)
        return 2
    require_auth = not args.no_auth
    user = args.user
    pw = args.password or secrets.token_urlsafe(9)
    token = base64.b64encode(f"{user}:{pw}".encode()).decode()
    page = render_live_page(args.interval).encode()

    class Handler(BaseHTTPRequestHandler):
        def _authed(self):
            return (not require_auth) or self.headers.get("Authorization", "") == f"Basic {token}"

        def do_GET(self):
            if not self._authed():
                self.send_response(401)
                self.send_header("WWW-Authenticate", 'Basic realm="HINEC DSE"')
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            path = self.path.split("?")[0]
            if path in ("/", "/index.html"):
                body, ctype = page, "text/html; charset=utf-8"
            elif path == "/status.json":
                try:
                    body = status_path.read_bytes()
                except Exception:
                    body = b"{}"
                ctype = "application/json"
            else:
                self.send_response(404)
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            self.send_response(200)
            self.send_header("Content-Type", ctype)
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *a):
            pass  # quiet

    srv = ThreadingHTTPServer((args.host, args.port), Handler)
    if require_auth:
        print(f"[serve] {d.name} at http://{args.host}:{args.port}  (HTTP Basic auth)")
        print(f"[serve] user: {user}")
        print(f"[serve] pass: {pw}")
    else:
        print(f"[serve] {d.name} at http://{args.host}:{args.port}  (NO AUTH)")
    sys.stdout.flush()
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


