# Results parsing (defensive: scorer JSON shape is confirmed against the first real cell)
# --------------------------------------------------------------------------------------
def _flatten_numbers(obj, prefix=""):
    out = {}
    if isinstance(obj, dict):
        for k, v in obj.items():
            out.update(_flatten_numbers(v, f"{prefix}{k}."))
    elif isinstance(obj, (int, float)) and not isinstance(obj, bool):
        out[prefix.rstrip(".")] = float(obj)
    return out


def parse_results(run_dir):
    """Extract headline metrics from <run_dir>/scoring/renauld2023/results.json.
    Returns None if absent/unparsable. Defensive about exact key names."""
    if not run_dir:
        return None
    p = REPO_ROOT / run_dir / "scoring" / "renauld2023" / "results.json"
    if not p.exists():
        return None
    try:
        data = json.loads(p.read_text())
    except Exception:
        return None
    flat = _flatten_numbers(data)

    def pick(*names):
        for n in names:
            if n in flat:
                return flat[n]
        for n in names:
            for k, v in flat.items():
                if k.split(".")[-1] == n:
                    return v
        return None

    m = {
        "mean_f1":    pick("mean_f1", "f1", "mean_F1", "F1"),
        "mean_OL":    pick("mean_OL", "OL", "mean_ol", "mean_overlap"),
        "mean_OR_gt": pick("mean_OR_gt", "OR_gt", "mean_or_gt", "mean_overreach"),
        "mean_OR_vs": pick("mean_OR_vs"),
        "VB":         pick("VB", "valid_bundles", "vb"),
        "VS":         pick("VS", "vs"),                       # valid-streamline COUNT
        "VS_ratio":   pick("VS_ratio", "vs_ratio"),           # purity fraction (0..1)
        "IS_ratio":   pick("IS_ratio"),                       # invalid-streamline fraction
        "total_streamlines": pick("total_streamlines"),
    }
    return m


# --------------------------------------------------------------------------------------
# Orchestrator
# --------------------------------------------------------------------------------------
def now_iso():
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def atomic_write(path: Path, text: str):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


class Orchestrator:
    RUN_DIR_RE = re.compile(r"^Run dir:\s+(\S+)", re.MULTILINE)

    def __init__(self, dse_dir, cells, parallel, source, do_score, refresh, base_cfg,
                 workers, stagger, prune_trk=False, prune_mat=False):
        self.dir = dse_dir
        self.cells = {c["id"]: c for c in cells}
        self.order = [c["id"] for c in cells]
        self.parallel = parallel
        self.workers = workers                 # per-cell MATLAB parpool workers (HINEC_MAX_WORKERS)
        self.stagger = stagger                 # min seconds between cell launches (avoid parpool stampede)
        self.prune_trk = prune_trk             # delete scoring/tracks.trk after each cell scores (zero-loss)
        self.prune_mat = prune_mat             # also delete tractography/tracks*.mat (loses tractogram, keeps scores)
        self.source = source
        self.do_score = do_score
        self.refresh = refresh
        self.base_cfg = base_cfg
        self.logs = dse_dir / "logs"
        self.status_path = dse_dir / "status.json"
        self.report_path = dse_dir / "report.html"
        self.running = {}          # cell_id -> subprocess.Popen
        self.rt = {}               # cell_id -> {fh, t0}  (runtime handles; NEVER persisted)
        self.state = {}            # cell_id -> per-cell state dict (JSON-serializable only)
        self.stop = False
        self.started_at = now_iso()
        self._load_or_init_state()

    # ---- state ------------------------------------------------------------------
    def _load_or_init_state(self):
        prior = {}
        if self.status_path.exists():
            try:
                prior = json.loads(self.status_path.read_text()).get("cells", {})
            except Exception:
                prior = {}
        for cid in self.order:
            c = self.cells[cid]
            p = prior.get(cid)
            if p and p.get("state") == "done" and p.get("metrics"):
                self.state[cid] = p                     # keep finished cells on resume
            else:
                self.state[cid] = {
                    **{k: c[k] for k in ("id", "algorithm", "field", "axes")},
                    "state": "queued", "stage": "queued", "pid": None,
                    "run_dir": None, "log": os.path.relpath(self.logs / f"cell_{cid}.log", REPO_ROOT),
                    "cmd": None, "started": None, "finished": None,
                    "elapsed_s": None, "returncode": None, "metrics": None, "error": None,
                }

    def _pending(self):
        return [cid for cid in self.order if self.state[cid]["state"] == "queued"]

    def persist(self):
        summary = self._summary()
        doc = {
            "dse_id": self.dir.name, "started_at": self.started_at, "updated": now_iso(),
            "parallel": self.parallel, "source": str(self.source), "score": self.do_score,
            "base_config": str(self.base_cfg), "summary": summary,
            "cells": self.state,
        }
        atomic_write(self.status_path, json.dumps(doc, indent=2, default=str))
        atomic_write(self.report_path, render_html(doc, self.refresh))

    def _summary(self):
        by = {"queued": 0, "running": 0, "done": 0, "failed": 0}
        best = None
        elapsed = []
        for s in self.state.values():
            by[s["state"]] = by.get(s["state"], 0) + 1
            if s.get("elapsed_s"):
                elapsed.append(s["elapsed_s"])
            f1 = (s.get("metrics") or {}).get("mean_f1")
            if f1 is not None and (best is None or f1 > best["mean_f1"]):
                best = {"id": s["id"], "mean_f1": f1}
        total = len(self.state)
        finished = by.get("done", 0) + by.get("failed", 0)
        avg = sum(elapsed) / len(elapsed) if elapsed else None
        remaining = total - finished
        eta = None
        if avg and remaining:
            waves = -(-remaining // max(self.parallel, 1))     # ceil
            eta = round(avg * waves)
        return {"total": total, **by, "finished": finished,
                "avg_cell_s": round(avg) if avg else None, "eta_s": eta,
                "best": best}

    # ---- launching / monitoring -------------------------------------------------
    def _launch(self, cid):
        c = self.cells[cid]
        cmd = ["bash", str(RUN_TRACT), str(self.base_cfg), "--source", str(self.source)]
        if self.do_score:
            cmd.append("--score")
        for k, v in c["overrides"].items():
            cmd += ["--set", f"{k}={v}"]
        logf = self.logs / f"cell_{cid}.log"
        fh = open(logf, "w")
        # Per-cell MATLAB environment. A UNIQUE MATLAB_PREFDIR relocates each MATLAB's
        # local-cluster job storage, so concurrent cells' parpools cannot collide
        # (the "job not in pending state" race). HINEC_MAX_WORKERS caps each cell's pool.
        prefdir = self.dir / "mprefs" / cid
        prefdir.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ)
        env["MATLAB_PREFDIR"] = str(prefdir)
        env["HINEC_MAX_WORKERS"] = str(self.workers)
        # own process group so we can tear down the whole tree (bash+matlab+python) cleanly
        proc = subprocess.Popen(cmd, cwd=str(REPO_ROOT), stdout=fh, stderr=subprocess.STDOUT,
                                start_new_session=True, env=env)
        self.running[cid] = proc
        self.rt[cid] = {"fh": fh, "t0": time.time()}   # runtime-only; not in self.state
        s = self.state[cid]
        s.update(state="running", stage="starting", pid=proc.pid, cmd=cmd, started=now_iso())
        print(f"[{now_iso()}] launch {cid}  pid={proc.pid}")

    def _find_run_dir(self, cid):
        logf = self.logs / f"cell_{cid}.log"
        try:
            m = self.RUN_DIR_RE.search(logf.read_text())
        except Exception:
            return None
        return m.group(1) if m else None

    def _detect_stage(self, cid, alive):
        s = self.state[cid]
        rd = s.get("run_dir")
        if rd is None:
            return "starting" if alive else s["stage"]
        rp = REPO_ROOT / rd
        if (rp / "scoring" / "renauld2023" / "results.json").exists():
            return "scoring" if alive else "done"
        if any((rp / "tractography").glob("tracks*.mat")):
            return "scoring" if self.do_score else "done"
        if rp.exists():
            return "tracking"
        return "starting"

    def _poll(self):
        for cid, proc in list(self.running.items()):
            s = self.state[cid]
            if s.get("run_dir") is None:
                s["run_dir"] = self._find_run_dir(cid)
            rc = proc.poll()
            if rc is None:
                s["stage"] = self._detect_stage(cid, alive=True)
                continue
            # finished
            rt = self.rt.pop(cid, {})
            if rt.get("fh"):
                rt["fh"].close()
            s["run_dir"] = s.get("run_dir") or self._find_run_dir(cid)
            metrics = parse_results(s["run_dir"])
            s["returncode"] = rc
            s["finished"] = now_iso()
            s["elapsed_s"] = round(time.time() - rt.get("t0", time.time()), 1)
            s["metrics"] = metrics
            self._prune(s["run_dir"])
            if rc == 0:
                s["state"], s["stage"] = "done", "done"
                if metrics is None:
                    s["error"] = "exit 0 but no results.json (scoring skipped/failed)"
            else:
                s["state"], s["stage"] = "failed", "failed"
                s["error"] = self._log_tail(cid)
            del self.running[cid]
            f1 = (metrics or {}).get("mean_f1")
            print(f"[{now_iso()}] {'done' if rc == 0 else 'FAIL'} {cid}  "
                  f"rc={rc} f1={f1} ({s['elapsed_s']}s)")

    def _log_tail(self, cid, n=25):
        try:
            lines = (self.logs / f"cell_{cid}.log").read_text().splitlines()
            return "\n".join(lines[-n:])
        except Exception:
            return None

    def _prune(self, run_dir):
        # After scoring, the .trk is pure scratch (regenerable from tracks.mat); optionally
        # the tracks.mat too. results.json / config / options are always kept.
        if not run_dir or not (self.prune_trk or self.prune_mat):
            return
        rd = REPO_ROOT / run_dir
        try:
            if self.prune_trk:
                trk = rd / "scoring" / "tracks.trk"
                if trk.exists():
                    trk.unlink()
            if self.prune_mat:
                for m in (rd / "tractography").glob("tracks*.mat"):
                    m.unlink()
        except Exception:
            pass

    def _teardown(self):
        for cid, proc in list(self.running.items()):
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
            except Exception:
                pass
            self.state[cid].update(state="queued", stage="queued", pid=None)
            rt = self.rt.pop(cid, {})
            if rt.get("fh"):
                rt["fh"].close()
        self.running.clear()
        # MATLAB clients + parpool workers survive their launcher's death; reap any process
        # whose cmdline references this DSE dir (safe: this orchestrator's cmdline does not).
        try:
            subprocess.run(["pkill", "-9", "-f", str(self.dir.resolve())],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)
        except Exception:
            pass

    def run(self):
        def on_sig(signum, frame):
            print(f"\n[{now_iso()}] signal {signum} — stopping (running cells re-queued for resume)")
            self.stop = True
        signal.signal(signal.SIGINT, on_sig)
        signal.signal(signal.SIGTERM, on_sig)

        print(f"[{now_iso()}] DSE {self.dir.name}: {len(self.order)} cells, "
              f"parallel={self.parallel}, workers={self.workers}, stagger={self.stagger}s, "
              f"score={self.do_score}")
        self.persist()
        last_launch = 0.0
        try:
            while not self.stop:
                # Launch at most one cell per `stagger` seconds so concurrent parpools
                # never start simultaneously (a simultaneous stampede crashes MATLAB workers).
                now = time.time()
                if (len(self.running) < self.parallel and self._pending()
                        and now - last_launch >= self.stagger):
                    self._launch(self._pending()[0])
                    last_launch = time.time()
                self._poll()
                self.persist()
                if not self.running and not self._pending():
                    break
                time.sleep(2)
        finally:
            if self.stop:
                self._teardown()
            self.persist()
        s = self._summary()
        print(f"[{now_iso()}] DSE finished: done={s['done']} failed={s['failed']} "
              f"queued={s['queued']} best={s['best']}")
        return 0 if s.get("failed", 0) == 0 else 1


