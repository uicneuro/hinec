def cmd_plan(args):
    cells = build_cells(args.grid)
    by = {}
    for c in cells:
        by[c["algorithm"]] = by.get(c["algorithm"], 0) + 1
    print(f"grid '{args.grid}': {len(cells)} cells  " +
          "  ".join(f"{k}={v}" for k, v in by.items()))
    for c in cells:
        print(f"  {c['id']:32s}  " + " ".join(f"{k}={v}" for k, v in c['overrides'].items()))
    return 0


def _new_dir():
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    d = REPO_ROOT / "hinec_runs" / f"dse_{ts}"
    return d


def cmd_run(args):
    cells = build_cells(args.grid)
    if args.limit:
        cells = cells[:args.limit]
    dse_dir = Path(args.dir).resolve() if args.dir else _new_dir()
    dse_dir.mkdir(parents=True, exist_ok=True)
    (dse_dir / "logs").mkdir(exist_ok=True)
    base_cfg = dse_dir / "dse_base.yml"
    if not base_cfg.exists():
        base_cfg.write_text(BASE_YAML)
    atomic_write(dse_dir / "manifest.json", json.dumps(
        {"grid": args.grid, "created": now_iso(), "parallel": args.parallel,
         "score": not args.no_score, "cells": cells}, indent=2))
    source = Path(args.source).resolve() if args.source else DEFAULT_SOURCE
    if not source.exists():
        print(f"error: source nim not found: {source}", file=sys.stderr)
        return 2
    orch = Orchestrator(dse_dir, cells, parallel=args.parallel, source=source,
                        do_score=not args.no_score, refresh=args.refresh, base_cfg=base_cfg,
                        workers=args.workers, stagger=args.stagger,
                        prune_trk=args.prune_trk, prune_mat=args.prune_mat)
    print(f"DSE dir: {dse_dir}")
    print(f"report : {dse_dir / 'report.html'}")
    return orch.run()


def cmd_report(args):
    d = Path(args.dir)
    doc = json.loads((d / "status.json").read_text())
    atomic_write(d / "report.html", render_html(doc, args.refresh))
    print(f"wrote {d / 'report.html'}")
    return 0


def cmd_status(args):
    doc = json.loads((Path(args.dir) / "status.json").read_text())
    s = doc["summary"]
    print(f"{doc['dse_id']}  updated {doc['updated']}")
    print(f"  total {s['total']}  done {s['done']}  running {s['running']}  "
          f"queued {s['queued']}  failed {s['failed']}")
    if s.get("best"):
        print(f"  best F1 {s['best']['mean_f1']:.4f}  ({s['best']['id']})")
    if s.get("eta_s"):
        print(f"  eta ~{s['eta_s']}s  (avg/cell {s.get('avg_cell_s')}s)")
    for cid, c in doc["cells"].items():
        if c["state"] == "running":
            print(f"  running {cid:32s} stage={c['stage']} pid={c['pid']} run={c['run_dir']}")
    return 0


def main():
    ap = argparse.ArgumentParser(description="HINEC tractography DSE orchestrator")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("plan", help="enumerate the design space and exit")
    p.add_argument("--grid", choices=list(GRIDS), default="full")
    p.set_defaults(func=cmd_plan)

    p = sub.add_parser("run", help="run the DSE (long-running)")
    p.add_argument("--grid", choices=list(GRIDS), default="full")
    p.add_argument("--parallel", type=int, default=6, help="max concurrent MATLAB cells")
    p.add_argument("--workers", type=int, default=8, help="parpool workers per cell (HINEC_MAX_WORKERS)")
    p.add_argument("--stagger", type=int, default=12, help="min seconds between cell launches (anti-stampede)")
    p.add_argument("--prune-trk", action="store_true", help="delete scoring/tracks.trk after each cell scores (zero-loss)")
    p.add_argument("--prune-mat", action="store_true", help="also delete tracks*.mat after scoring (keeps results.json)")
    p.add_argument("--limit", type=int, default=0, help="run only the first N cells (validation)")
    p.add_argument("--dir", default="", help="reuse/resume an existing dse_<ts> dir")
    p.add_argument("--source", default="", help="preprocessed nim (default data/ismrm2015/ismrm2015.mat)")
    p.add_argument("--refresh", type=int, default=20, help="report auto-refresh seconds (0=off)")
    p.add_argument("--no-score", action="store_true", help="track only, skip scoring")
    p.set_defaults(func=cmd_run)

    p = sub.add_parser("report", help="regenerate report.html from status.json")
    p.add_argument("--dir", required=True)
    p.add_argument("--refresh", type=int, default=20)
    p.set_defaults(func=cmd_report)

    p = sub.add_parser("status", help="print a live status summary")
    p.add_argument("--dir", required=True)
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("serve", help="serve a LIVE auth-gated dashboard (front with cloudflared/ssh -L)")
    p.add_argument("--dir", required=True)
    p.add_argument("--host", default="127.0.0.1", help="bind host (127.0.0.1 = localhost only)")
    p.add_argument("--port", type=int, default=8787)
    p.add_argument("--interval", type=float, default=5, help="client poll seconds")
    p.add_argument("--user", default="hinec", help="HTTP Basic auth username")
    p.add_argument("--password", default="", help="HTTP Basic auth password (random if omitted)")
    p.add_argument("--no-auth", action="store_true", help="disable HTTP Basic auth (open dashboard)")
    p.set_defaults(func=cmd_serve)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
