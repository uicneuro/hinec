#!/usr/bin/env python3
"""
HINEC tractography Design-Space Exploration (DSE) orchestrator.

WHAT IT DRIVES
--------------
The HINEC pipeline is preprocess-once / iterate-tractography. This tool drives the
tractography-only entry point:

    bin/run_tractography.sh <base_config> --score --set key=value ...

which is SYNCHRONOUS: for one cell it runs MATLAB tractography, converts tracks to TRK,
then runs the scilpy Renauld-2023 scorer, all in one blocking process, and prints
"Run dir:  hinec_runs/run_<ts>_<cfg><suffix>" to stdout. Output per cell:
    <run_dir>/tractography/tracks*.mat            (tracking done)
    <run_dir>/scoring/renauld2023/results.json    (scoring done -> mean_f1/mean_OL/...)

So a cell's PIPELINE STAGE is observable without cooperation from the child:
    run_dir missing              -> starting
    run_dir, no tracks*.mat      -> tracking
    tracks*.mat, no results.json -> scoring
    results.json present         -> done

DESIGN SPACE
------------
Every tractography parameter is `--set`-addressable, so the whole space is driven from
ONE controlled base config (dse_base.yml, written into the run dir). Each cell overrides
ONLY the axis under study; everything else is held fixed for a fair comparison.

    hinec:    field {dti,csd} x interp_method {trilinear,cubic}
              x sel_power {0,8,16,32} x integration_order {1,2,4,5}
    mmf:      field {dti,csd} x integrator {rk4,rkf45} x frame_sel_power {8,16,32}
    standard: FACT baseline (dti, Euler)

WHAT IT PRODUCES  (hinec_runs/dse_<ts>/)
    dse_base.yml    the controlled base config used by every cell
    manifest.json   the enumerated design space (immutable record of the run)
    status.json     live state of every cell (atomic writes; resume reads this)
    report.html     self-contained, auto-refreshing dashboard (view in any browser)
    logs/cell_<id>.log   combined stdout/stderr of each cell's run_tractography.sh

USAGE
    scripts/dse/dse.py plan   [--grid full|quick|smoke]
    scripts/dse/dse.py run    [--grid full|quick|smoke] [--parallel N] [--limit N]
                              [--dir PATH] [--refresh SECS] [--no-score]
    scripts/dse/dse.py report --dir hinec_runs/dse_<ts>
    scripts/dse/dse.py status --dir hinec_runs/dse_<ts>

Resume: `run --dir <existing dse dir>` re-reads status.json and only runs cells that are
not already `done`. stdlib-only; no third-party deps.
"""

