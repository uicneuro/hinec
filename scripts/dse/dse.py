# Abbreviations for compact, stable cell ids
_INTERP_ABBR = {"trilinear": "tri", "cubic": "cub", "none": "none"}
_AXIS_ABBR = {"act_enabled": "act", "termination_fa": "tfa", "seed_density": "sd",
              "angle_thresh": "ang", "step_size": "ss", "min_length": "ml", "mmf_anchor": "anc"}
_STD_AXES = {"algorithm", "field", "interp_method", "sel_power",
             "integration_order", "integrator", "frame_sel_power"}


def _product(axes):
    """Cartesian product over an ordered dict of axis -> list-of-values."""
    keys = list(axes.keys())
    combos = [[]]
    for k in keys:
        combos = [c + [(k, v)] for c in combos for v in axes[k]]
    return [dict(c) for c in combos]


def build_cells(grid_name):
    """Enumerate the design space into a deterministic, ordered list of cell dicts."""
    grid = GRIDS[grid_name]
    cells = []
    for algo in ("standard", "hinec", "mmf"):
        if algo not in grid:
            continue
        for axes in _product(grid[algo]):
            overrides = {"algorithm": algo, **axes}
            cells.append({
                "id": _cell_id(algo, axes),
                "algorithm": algo,
                "field": axes.get("field", "dti"),
                "axes": axes,
                "overrides": overrides,
            })
    # de-dup (defensive) and keep enumeration order
    seen, out = set(), []
    for c in cells:
        if c["id"] in seen:
            continue
        seen.add(c["id"])
        out.append(c)
    return out


def _cell_id(algo, axes):
    if algo == "hinec":
        base = "hinec-{f}-{i}-sp{s}-io{o}".format(
            f=axes["field"], i=_INTERP_ABBR.get(axes["interp_method"], axes["interp_method"]),
            s=axes["sel_power"], o=axes["integration_order"])
    elif algo == "mmf":
        base = "mmf-{f}-{i}-{g}-fsp{s}".format(
            f=axes["field"], i=_INTERP_ABBR.get(axes["interp_method"], axes["interp_method"]),
            g=axes["integrator"], s=axes["frame_sel_power"])
    elif algo == "standard":
        base = "standard-{f}-io{o}".format(f=axes["field"], o=axes["integration_order"])
    else:
        base = algo
    # append any non-standard swept axes (e.g. act_enabled, termination_fa) so cells stay unique
    for k in sorted(k for k in axes if k not in _STD_AXES):
        v = axes[k]
        vs = ("1" if v else "0") if isinstance(v, bool) else str(v)
        base += "-{}{}".format(_AXIS_ABBR.get(k, k), vs)
    return base


